const cache = new Map<string, HTMLCanvasElement>();

/** Rendu d'un sprite (1 px = 1 pixel) dans un canvas mis en cache. */
export function spriteCanvas(id: string, flip = false): HTMLCanvasElement {
  const ck = `${id}|${flip ? 1 : 0}`;
  const hit = cache.get(ck);
  if (hit) return hit;
  const v = VARIANTS[id] ?? { sprite: SPRITES[id] ? id : "stone" };
  const def = SPRITES[v.sprite] ?? SPRITES.stone;
  const pal: Palette = { k: K, w: W, ...def.pal, ...(v.pal ?? {}) };
  const c = document.createElement("canvas");
  c.width = 16;
  c.height = 16;
  const g = c.getContext("2d")!;
  def.rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (!ch || ch === ".") continue;
      const col = pal[ch];
      if (!col) continue;
      g.fillStyle = col;
      g.fillRect(flip ? 15 - x : x, y, 1, 1);
    }
  });
  cache.set(ck, c);
  return c;
}

/** Silhouette unie d'un sprite (flash de coup). */
export function silhouetteCanvas(id: string, flip = false, color = "#ffffff"): HTMLCanvasElement {
  const ck = `sil|${id}|${flip ? 1 : 0}|${color}`;
  const hit = cache.get(ck);
  if (hit) return hit;
  const c = document.createElement("canvas");
  c.width = 16;
  c.height = 16;
  const g = c.getContext("2d")!;
  g.drawImage(spriteCanvas(id, flip), 0, 0);
  g.globalCompositeOperation = "source-in";
  g.fillStyle = color;
  g.fillRect(0, 0, 16, 16);
  cache.set(ck, c);
  return c;
}

export function isDiagonal(id: string): boolean {
  const v = VARIANTS[id];
  return SPRITES[v?.sprite ?? id]?.diagonal === true;
}
