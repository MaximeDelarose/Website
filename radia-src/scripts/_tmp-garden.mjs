const P = (i) => ({ x: box.x + lay[i].x + lay[i].w / 2, y: box.y + lay[i].y + lay[i].h * 0.6 });
const plotXY = (i) => { const cols = 3; const gapX = Math.max(6, box.width * 0.03); const cw = (box.width - 28 - gapX * 2) / 3; return { x: box.x + 14 + (i % 3) * (cw + gapX) + cw / 2, y: box.y + box.height * 0.5 + Math.floor(i / 3) * 0 }; };
