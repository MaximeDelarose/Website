await page.evaluate(() => { const g = window.RADIA.save.data.world.garden; g.plots[0].plantedAt -= 9000; g.plots[1].plantedAt -= 18000; });
await page.waitForTimeout(800);
await page.screenshot({ path: S + 'g-growing.png' });
