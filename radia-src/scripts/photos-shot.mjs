import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.addInitScript(() => localStorage.setItem('radia-save-v1', JSON.stringify({ v: 1, story: { step: 30, stepKey: 'level:10', history: [], choices: {} }, levels: {}, memories: ['flowers','nord'] })));
await page.goto(`http://localhost:4173/#k=${process.env.PHOTO_KEY ?? ''}`, { waitUntil: 'networkidle' }); await page.waitForTimeout(1500);
await page.getByText('SOUVENIRS').first().click(); await page.waitForTimeout(600);
await page.getByText('Photos', { exact: true }).click(); await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/ph-album.png' });
await page.locator('.photo-grid .polaroid').first().click(); await page.waitForTimeout(600);
await page.screenshot({ path: 'shots/ph-full.png' });
console.log('errors', errs);
await browser.close();
