// --- accents (ajoutés au-dessus d'une lettre de base) ---
const MARK = { acute: ['...#.', '..#..'], grave: ['.#...', '..#..'], circ: ['..#..', '.#.#.'], trema: ['.....', '.#.#.'] };
const accent = (ch, base, mark) => {
  const b = G[base];
  const w = Math.max(...b.rows.map((r) => r.length));
  const m = MARK[mark].map((r) => r.slice(0, w).padEnd(w, '.'));
  if (base === base.toUpperCase() && base !== base.toLowerCase()) G[ch] = { rows: [...m, ...b.rows], top: -2 };
  else {
    const rows = b.rows.slice();
    rows[0] = m[0];
    rows[1] = m[1];
    G[ch] = { rows, top: 0 };
  }
};
accent('é', 'e', 'acute'); accent('è', 'e', 'grave'); accent('ê', 'e', 'circ'); accent('ë', 'e', 'trema');
accent('à', 'a', 'grave'); accent('â', 'a', 'circ'); accent('ô', 'o', 'circ'); accent('ù', 'u', 'grave');
accent('û', 'u', 'circ'); accent('ü', 'u', 'trema'); accent('î', 'i', 'circ'); accent('ï', 'i', 'trema');
