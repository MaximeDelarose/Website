export const LINE = 11; // hauteur d'une ligne (avec accents et jambages)
const TOP = 2; // décalage : ligne 0 du glyphe = ligne 2 de la cellule

function glyph(ch) {
  return G[ch] || G[ch.normalize('NFD')[0]] || G['?'];
}

export function measure(str, scale = 1) {
  let w = 0;
  for (const ch of str) w += Math.max(...glyph(ch).rows.map((r) => r.length)) + 1;
  return { w: Math.max(0, w - 1) * scale, h: LINE * scale };
}

/** Dessine `str` dans un canevas (pixels pleins, contour d'1 px). Renvoie le canevas. */
export function render(str, { color = '#fff6dc', outline = '#1a1424', scale = 1 } = {}) {
  const { w: tw } = measure(str, 1);
  const pad = outline ? 1 : 0;
  const W = tw * scale + pad * 2, H = LINE * scale + pad * 2;
  const on = new Uint8Array(W * H);
  let x = 0;
  for (const ch of str) {
    const g = glyph(ch);
    const gw = Math.max(...g.rows.map((r) => r.length));
    g.rows.forEach((row, j) => {
      for (let i = 0; i < row.length; i++)
        if (row[i] === '#')
          for (let dy = 0; dy < scale; dy++)
            for (let dx = 0; dx < scale; dx++) on[(pad + (TOP + g.top + j) * scale + dy) * W + pad + (x + i) * scale + dx] = 1;
    });
    x += gw + 1;
  }
  const c = document.createElement('canvas');
  c.width = Math.max(1, W);
  c.height = H;
  const ctx = c.getContext('2d');
  const img = ctx.createImageData(c.width, H);
  const hex = (s) => [1, 3, 5].map((i) => parseInt(s.slice(i, i + 2), 16));
  const fc = hex(color), oc = outline ? hex(outline) : null;
  for (let y = 0; y < H; y++)
    for (let xx = 0; xx < W; xx++) {
      const i = y * W + xx, p = i * 4;
      if (on[i]) {
        img.data.set([...fc, 255], p);
      } else if (oc && ((xx > 0 && on[i - 1]) || (xx < W - 1 && on[i + 1]) || (y > 0 && on[i - W]) || (y < H - 1 && on[i + W]))) {
        img.data.set([...oc, 255], p);
      }
    }
  ctx.putImageData(img, 0, 0);
  return c;
}
